-- Fixture database "supabase_like": mimics Supabase pg_net. Its queue table is
-- writable and its http_post function executable by PUBLIC, so any role that
-- can connect, even one granted only SELECT, can make the database send HTTP
-- requests unless the session is read-only.

CREATE SCHEMA net;

CREATE TABLE net.http_request_queue (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method     text NOT NULL,
    url        text NOT NULL,
    body       text,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE FUNCTION net.http_post(url text, body text) RETURNS void
LANGUAGE sql
SECURITY INVOKER
AS $$
    INSERT INTO net.http_request_queue (method, url, body) VALUES ('POST', $1, $2)
$$;

GRANT USAGE ON SCHEMA net TO PUBLIC;
GRANT INSERT, UPDATE, DELETE ON net.http_request_queue TO PUBLIC;
GRANT EXECUTE ON FUNCTION net.http_post(text, text) TO PUBLIC;

CREATE TABLE public.profiles (
    id           int PRIMARY KEY,
    display_name text NOT NULL
);
INSERT INTO public.profiles (id, display_name)
SELECT g, 'Profile ' || g FROM generate_series(1, 5) AS g;
GRANT SELECT ON public.profiles TO ro_supabase;

ANALYZE;
